def load_norm(path, sr=1000):
    sig, _ = librosa.load(path, sr=sr, mono=True)
    sig = sig.astype(np.float32)
    m = np.max(np.abs(sig))
    return sig / m if m > 1e-8 else sig

def mix_fixed_SNR(signal, noise, snr_db):
    Ps = np.sum(signal**2) / len(signal)
    Pn = np.sum(noise**2) / len(noise)
    if Pn < 1e-10:
        return signal
    K = (Ps / Pn) * 10**(-snr_db / 10)
    return (signal + np.sqrt(K) * noise).astype(np.float32)

def denoise_signal(model, signal, frame_len=800):
    orig_len = len(signal)
    m = np.max(np.abs(signal))
    if m < 1e-8:
        return signal
    sig_norm = signal / m
    pad = frame_len - (orig_len % frame_len)
    if pad != frame_len:
        sig_norm = np.concatenate([sig_norm, np.zeros(pad, dtype=np.float32)])
    segments = sig_norm.reshape(-1, frame_len, 1)
    output = model.predict(segments, batch_size=16, verbose=0)
    return (output.flatten()[:orig_len] * m).astype(np.float32)

