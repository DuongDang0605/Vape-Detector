def load_and_fft(wav_path):
    try:
        audio, sr = librosa.load(wav_path, sr=None, mono=True)
        if sr != TARGET_SR:
            audio = resample(audio, int(len(audio) * TARGET_SR / sr))
        if len(audio) < N_SAMPLES:
            audio = np.pad(audio, (0, N_SAMPLES - len(audio)))
        else:
            audio = audio[:N_SAMPLES]
        fft = np.abs(np.fft.rfft(audio))[:FFT_SIZE]
        fft = fft / (np.max(fft) + 1e-8)
        return fft
    except:
        return None

def build_split(ids):
    X, y = [], []
    for fid in tqdm(ids):
        for path, label in file_groups[fid]:
            fft = load_and_fft(path)
            if fft is not None:
                X.append(fft)
                y.append(label)
    return np.array(X)[..., np.newaxis], np.array(y)

