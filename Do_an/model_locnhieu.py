utils_code = '''
import numpy as np
import math

def mix_fixed_SNR(Signal, Noise, Desired_SNR_dB):
    Npts = len(Signal)
    Signal_Power = np.sum(abs(Signal)*abs(Signal)) / Npts
    Noise_Power = np.sum(abs(Noise)*abs(Noise)) / Npts
    K = (Signal_Power / Noise_Power) * 10**(-Desired_SNR_dB / 10)
    New_Noise = np.sqrt(K) * Noise
    Noisy_Signal = Signal + New_Noise
    return Noisy_Signal

def SI_SNR(est, egs):
    est = np.squeeze(est)
    egs = np.squeeze(egs)
    length = len(est)
    _s = est[0:length]
    s = egs[0:length]
    noise = _s - s
    noise_power = sum(pow(noise, 2)) / len(noise)
    pre_signal_power = sum(pow(s, 2)) / len(s)
    snr = 10 * math.log10(pre_signal_power / noise_power)
    return snr

def rmse(predictions, targets):
    return np.sqrt(((predictions - targets) ** 2).mean())

def prd(noisy, targets):
    return np.sqrt((((noisy - targets) ** 2).mean()) / (((noisy) ** 2).mean()))

def check_SNR_non_merged(Xtest, Ytest, SNR, model):
    est = model.predict(np.array(Xtest))
    shape = est.shape[0]
    snr_array  = np.zeros(shape)
    prd_array  = np.zeros(shape)
    rmse_array = np.zeros(shape)
    for L in range(shape):
        snr_array[L]  = SI_SNR(est[L], Ytest[L])
        prd_array[L]  = prd(Xtest[L], est[L])
        rmse_array[L] = rmse(est[L], Ytest[L])
    print("------")
    print(f"REAL_SNR      : {SNR}")
    print(f"PREDICTED_SNR : {np.mean(snr_array):.4f}")
    print(f"PRD           : {np.mean(prd_array):.4f}")
    print(f"RMSE          : {np.mean(rmse_array):.4f}")
    return est

def mergeX(X_train, seg):
    index = 0
    merge = []
    for L in range(int(X_train.shape[0] / seg)):
        temp = X_train[index]
        for i in range(index, index + seg - 1):
            temp = np.concatenate([temp, X_train[i + 1]])
        temp = temp / max(abs(temp))
        merge.append(temp)
        index += seg
    return np.array(merge)
'''

