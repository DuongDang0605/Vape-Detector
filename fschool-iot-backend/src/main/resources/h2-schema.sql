CREATE TABLE IF NOT EXISTS sensor_measurement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id VARCHAR(100) NOT NULL,
    boot_id VARCHAR(100) NOT NULL,
    sequence_number BIGINT NOT NULL,
    measured_at TIMESTAMP WITH TIME ZONE NOT NULL,
    received_at TIMESTAMP WITH TIME ZONE NOT NULL,
    temperature DOUBLE PRECISION NOT NULL,
    humidity DOUBLE PRECISION NOT NULL,
    pm25 INTEGER NOT NULL,
    sraw_voc INTEGER NOT NULL,
    edge_status VARCHAR(40) NOT NULL CHECK (edge_status IN ('CLEAN', 'VAPE_DETECTED')),
    buffered_message BOOLEAN NOT NULL,
    raw_payload CLOB NOT NULL,
    CONSTRAINT uk_measurement_device_boot_sequence
        UNIQUE (device_id, boot_id, sequence_number)
);

-- Firmware Final chi con hai trang thai. Chuan hoa du lieu cu truoc khi doc.
UPDATE sensor_measurement
SET edge_status = 'CLEAN'
WHERE edge_status IN ('STEAM_EXCLUDED', 'CHEMICAL_EXCLUDED');

CREATE INDEX IF NOT EXISTS ix_measurement_device_measured_at
    ON sensor_measurement(device_id, measured_at DESC);
